use crate::{RLookup, RLookupKey, RLookupKeyFlag, lookup::TRANSIENT_FLAGS};
use sorting_vector::{RSSortingVector, RSSortingVectorRef};
use std::{borrow::Cow, ffi::CStr, fmt, mem::ManuallyDrop};
use thin_vec::ThinVec;
use value::SharedValue;

/// Where a row reads its sorting values from, which [`RLookupRow::sorting_sparse`] tells apart.
///
/// A dense vector is never resized, so the row keeps a bitwise copy of its buffer pointer. A sparse
/// vector grows when a partial update adds a value, which may move its buffer while the row, held
/// by a cursor or across the safe loader, still exists. The row therefore keeps a pointer to the
/// vector itself, which lives in the document metadata the row's result keeps alive, and reads
/// the buffer from it on every lookup.
union SortingSource<'a> {
    dense: ManuallyDrop<RSSortingVectorRef<'a>>,
    sparse: *const RSSortingVector,
}

/// Row data for a lookup key. This abstracts the question of if the data comes from a borrowed sorting vector slice
/// or from dynamic values stored in the row during processing.
///
/// The C-visible layout comes from the `OpaqueRLookupRow` wrapper (which is
/// `#[repr(C, align(8))]` and `#[cheadergen::config(rename = "RLookupRow")]`).
/// Force this internal type to opaque so cheadergen does not warn about it
/// being reached by value through `SearchResult._row_data` — both names emit
/// to the same C tag, and the wrapper provides the actual layout.
#[cheadergen::config(export, opaque)]
pub struct RLookupRow<'a> {
    /// A reference to the sorting vector.
    sorting_vector: SortingSource<'a>,

    /// Whether [`Self::sorting_vector`] holds a sparse vector, in which case its `sparse` member
    /// is the active one and points at a vector that is valid for `'a`; otherwise `dense` is.
    /// Kept beside the reference so that a lookup in the common, dense, layout does not have to
    /// inspect the vector to know.
    sorting_sparse: bool,

    /// Dynamic values obtained from prior processing
    dyn_values: ThinVec<Option<SharedValue>>,

    /// The number of values in [`RLookupRow::dyn_values`] that are `is_some()`. Note that this
    /// is not the length of [`RLookupRow::dyn_values`]
    num_dyn_values: u32,
}

impl fmt::Debug for RLookupRow<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // NB: we purposefully DO NOT include the sorting_vector and dyn_values fields here,
        // so we don't accidentally leak user-data into log messages!
        f.debug_struct("RLookupRow")
            .field("num_dyn_values", &self.num_dyn_values)
            .finish_non_exhaustive()
    }
}

impl<'a> Default for RLookupRow<'a> {
    fn default() -> Self {
        Self::new()
    }
}

impl<'a> RLookupRow<'a> {
    /// Creates a new `RLookupRow` with an empty [`RLookupRow::dyn_values`] vector and
    /// a [`RLookupRow::sorting_vector`] of the given length.
    #[inline]
    pub const fn new() -> Self {
        Self {
            sorting_vector: SortingSource {
                dense: ManuallyDrop::new(RSSortingVectorRef::empty()),
            },
            sorting_sparse: false,
            dyn_values: ThinVec::new(),
            num_dyn_values: 0,
        }
    }

    /// Returns the length of [`RLookupRow::dyn_values`].
    #[inline]
    pub fn len(&self) -> usize {
        self.dyn_values.len()
    }

    /// Returns true if the [`RLookupRow::dyn_values`] vector is empty.
    #[inline]
    pub fn is_empty(&self) -> bool {
        self.dyn_values.is_empty()
    }

    /// Readonly access to the [`RLookupRow::dyn_values`] vector that has been generated by prior processing.
    ///
    /// The function [`RLookupRow::write_key`] can be used to write values to this vector.
    #[inline]
    pub fn dyn_values(&self) -> &[Option<SharedValue>] {
        &self.dyn_values
    }

    /// Sets the capacity of the [`RLookupRow::dyn_values`] vector to the given capacity.
    /// It fills up the vector with None values to the given capacity.
    /// This is useful to preallocate memory for the row if you know the number of values that will be written to it.
    pub fn set_dyn_capacity(&mut self, capacity: usize) {
        self.dyn_values.resize(capacity, None);
    }

    /// The dense sorting vector the row reads; only for a row whose layout is dense.
    #[inline]
    fn dense_sorting_vector(&self) -> &RSSortingVectorRef<'a> {
        debug_assert!(!self.sorting_sparse);
        // SAFETY: `dense` is the active member when `sorting_sparse` is false, see its docs.
        unsafe { &self.sorting_vector.dense }
    }

    /// The sparse sorting vector the row reads, which the owner of the vector may have grown
    /// since the row was given it; only for a row whose layout is sparse.
    #[inline]
    fn sparse_sorting_vector(&self) -> Option<&RSSortingVector> {
        debug_assert!(self.sorting_sparse);
        // SAFETY: `sparse` is the active member when `sorting_sparse` is true.
        let vector = unsafe { self.sorting_vector.sparse };
        // SAFETY: it points at a vector that outlives the row, see its docs.
        unsafe { vector.as_ref() }
    }

    /// Readonly access to the sorting vector values as a slice, one per sort index.
    ///
    /// Empty if the row has no sorting vector or its sorting vector is sparse; use
    /// [`Self::sorting_value`] to read by sort index whatever the layout.
    #[inline]
    pub fn sorting_vector(&self) -> &'a [SharedValue] {
        if self.sorting_sparse {
            &[]
        } else {
            self.dense_sorting_vector().as_slice()
        }
    }

    /// The value the row's sorting vector holds for sort index `idx`, if it holds one.
    ///
    /// For a dense sorting vector that is the slot, which holds the null sentinel where the
    /// document has no value.
    #[inline]
    pub fn sorting_value(&self, idx: usize) -> Option<&SharedValue> {
        if self.sorting_sparse {
            self.sparse_sorting_vector()?.get_by_index(idx)
        } else {
            self.dense_sorting_vector().as_slice().get(idx)
        }
    }

    /// Whether the row's sorting vector uses the sparse layout.
    #[inline]
    pub const fn is_sparse(&self) -> bool {
        self.sorting_sparse
    }

    /// Borrow a sorting vector for the row.
    pub fn set_sorting_vector(&mut self, sv: Option<&'a RSSortingVector>) {
        self.set_sorting_vector_with_layout(sv, sv.is_some_and(RSSortingVector::is_sparse));
    }

    /// Borrow a sorting vector for the row whose layout the caller already knows, so that
    /// attaching it does not touch the vector: it may be one a query never reads.
    ///
    /// `sparse` must be whether `sv` uses the sparse layout. A sparse vector is read through `sv`
    /// for as long as the row lives, so `sv` must be the vector where its owner keeps it, not a
    /// copy, and its owner may add values to it meanwhile.
    pub const fn set_sorting_vector_with_layout(
        &mut self,
        sv: Option<&'a RSSortingVector>,
        sparse: bool,
    ) {
        // We use [`RSSortingVectorRef`], a pointer-sized borrowed view, to avoid
        // dereferencing the `ThinVec` header here. This is a performance optimization
        // for hot paths where this function is called frequently and the sorting vector
        // being set may not need to be dereferenced later on.
        match sv {
            Some(sv) if sparse => {
                self.sorting_vector = SortingSource {
                    sparse: std::ptr::from_ref(sv),
                };
                self.sorting_sparse = true;
            }
            Some(sv) => {
                self.sorting_vector = SortingSource {
                    dense: ManuallyDrop::new(RSSortingVectorRef::from_ref(sv)),
                };
                self.sorting_sparse = false;
            }
            None => {
                self.sorting_vector = SortingSource {
                    dense: ManuallyDrop::new(RSSortingVectorRef::empty()),
                };
                self.sorting_sparse = false;
            }
        }
    }

    /// The number of values in [`RLookupRow::dyn_values`] that are `is_some()`. Note that this
    /// is not the length of [`RLookupRow::dyn_values`]
    #[inline]
    pub const fn num_dyn_values(&self) -> u32 {
        self.num_dyn_values
    }

    /// Retrieves an item from the given `RLookupRow` based on the provided `RLookupKey`.
    /// The function first checks for dynamic values, and if not found, it checks the sorting vector
    /// if the `SvSrc` flag is set in the key.
    /// If the item is not found in either location, it returns `None`.
    #[inline]
    pub fn get(&self, key: &RLookupKey) -> Option<&SharedValue> {
        // Check dynamic values first
        if let Some(Some(val)) = self.dyn_values().get(key.dstidx as usize) {
            return Some(val);
        }

        // If not found in dynamic values, check the sorting vector if the SvSrc flag is set
        if key.flags.contains(RLookupKeyFlag::SvSrc) {
            if self.sorting_sparse {
                return self.sparse_sorting_value(key.svidx as usize);
            }
            self.dense_sorting_value(key)
        } else {
            None
        }
    }

    /// [`Self::get`] for a row known to hold no sparse sorting vector: no test of the layout. For
    /// loops that look up many keys in a row, which can test [`Self::is_sparse`] once.
    #[inline]
    pub fn get_dense(&self, key: &RLookupKey) -> Option<&SharedValue> {
        debug_assert!(!self.sorting_sparse);
        if let Some(Some(val)) = self.dyn_values().get(key.dstidx as usize) {
            return Some(val);
        }
        if key.flags.contains(RLookupKeyFlag::SvSrc) {
            self.dense_sorting_value(key)
        } else {
            None
        }
    }

    #[inline]
    fn dense_sorting_value(&self, key: &RLookupKey) -> Option<&SharedValue> {
        // Sorting vector slots that were never written hold the null sentinel.
        // Filter it out so callers see `None` for absent fields, mirroring the C
        // guard in `RLookupRow_Get`:
        //   `if (ret != NULL && ret == RSValue_NullStatic()) ret = NULL;`
        self.dense_sorting_vector()
            .as_slice()
            .get(key.svidx as usize)
            .filter(|v| !v.is_null_static())
    }

    /// The sparse counterpart of [`Self::dense_sorting_value`], kept out of line so that the dense
    /// lookup stays as small as it was.
    #[inline(never)]
    fn sparse_sorting_value(&self, idx: usize) -> Option<&SharedValue> {
        self.sparse_sorting_vector()?
            .get_by_index(idx)
            .filter(|v| !v.is_null_static())
    }

    /// Write a value to the lookup table in [`RLookupRow::dyn_values`]. Key must already be registered, and not
    /// refer to a read-only (SVSRC) key.
    pub fn write_key(&mut self, key: &RLookupKey, val: SharedValue) -> Option<SharedValue> {
        let idx = key.dstidx;
        if self.dyn_values.len() <= idx as usize {
            self.set_dyn_capacity((idx + 1) as usize);
        }

        let prev = self.dyn_values[idx as usize].replace(val);

        if prev.is_none() {
            self.num_dyn_values += 1;
        }

        prev
    }

    /// Moves a dynamic value for `key` into `dst` without changing its reference count.
    pub fn move_dynamic_key_to(&mut self, key: &RLookupKey, dst: &mut Self) {
        if let Some(value) = self
            .dyn_values
            .get_mut(key.dstidx as usize)
            .and_then(Option::take)
        {
            self.num_dyn_values -= 1;
            dst.write_key(key, value);
        }
    }

    /// Write a value to the lookup table *by-name*. This is useful for 'dynamic' keys
    /// for which it is not necessary to use the boilerplate of getting an explicit
    /// key.
    pub fn write_key_by_name(
        &mut self,
        rlookup: &mut RLookup<'a>,
        name: impl Into<Cow<'a, CStr>>,
        val: SharedValue,
    ) {
        let name = name.into();
        self.write_key_by_name_bytes(rlookup, name.to_bytes(), val);
    }

    /// Like [`Self::write_key_by_name`], accepting name bytes without a NUL terminator.
    /// Existing names need no [`CStr`] validation; new names are copied into the lookup.
    ///
    /// # Panics
    ///
    /// Panics if `name` contains a NUL byte.
    pub fn write_key_by_name_bytes(
        &mut self,
        rlookup: &mut RLookup<'a>,
        name: &[u8],
        val: SharedValue,
    ) {
        let key = rlookup.get_or_create_key_by_name(name);
        self.write_key(key, val);
    }

    /// Wipes the row, retaining its memory but decrementing the ref count of any included instance of `T`.
    /// This does not free all the memory consumed by the row, but simply resets
    /// the row data (preserving any caches) so that it may be refilled.
    /// Also clears the sorting vector.
    #[inline]
    pub fn wipe(&mut self) {
        let mut remaining = self.num_dyn_values;
        for value in self.dyn_values.iter_mut() {
            if remaining == 0 {
                break;
            }
            if value.is_some() {
                drop(value.take());
                remaining -= 1;
            }
        }
        self.num_dyn_values = 0;
        self.sorting_vector = SortingSource {
            dense: ManuallyDrop::new(RSSortingVectorRef::empty()),
        };
        self.sorting_sparse = false;
    }

    /// Resets the row, clearing the dynamic values. This effectively wipes the row and deallocates the memory used for dynamic values.
    ///
    /// It does not affect the sorting vector.
    pub fn reset_dyn_values(&mut self) {
        self.num_dyn_values = 0;
        self.dyn_values = ThinVec::new();
    }

    /// Write fields from a source row into this row.
    ///
    /// Iterate through the source lookup keys, if it finds a corresponding key in the destination
    /// lookup by name, then it's value is written to this row as a destination.
    ///
    /// If a source key has no value in the source row, it is skipped.
    ///
    /// If a source key is not found in the destination lookup the function will either create it or panic
    /// depending on the value of `create_missing_keys`.
    ///
    /// # Arguments
    ///
    /// - `dst_lookup`: The destination lookup containing the schema of this row, must be the associated lookup of `self`.
    /// - `src_row`: The source row from which to copy values.
    /// - `src_lookup`: The source lookup containing the schema of the source row, must be the associated lookup of `src_row`.
    /// - `create_missing_keys`: Whether keys missing in `dst_lookup` should be created automatically, or force a panic.
    pub fn copy_fields_from(
        &mut self,
        dst_lookup: &mut RLookup<'a>,
        src_row: &Self,
        src_lookup: &RLookup<'a>,
        create_missing_keys: bool,
    ) {
        let dst_row = self;

        for src_key in src_lookup.iter() {
            if let Some(value) = src_row.get(src_key) {
                // Find corresponding key in destination lookup
                let dst_key = match dst_lookup.find_key_by_name(src_key.name()) {
                    Some(k) => k.into_current().unwrap(),
                    None if create_missing_keys => {
                        // Inherit non-transient flags from source.
                        let flags = src_key.flags & !TRANSIENT_FLAGS;

                        // Key doesn't exist in destination - create it on demand.
                        // This can happen with LOAD * where keys are created dynamically.
                        dst_lookup
                            .get_key_write(src_key.name().clone(), flags)
                            .unwrap()
                    }
                    _ => panic!("all source keys must exist in destination"),
                };

                // Write fields to destination
                dst_row.write_key(dst_key, value.clone());
            }
        }
    }

    /// Move data from the source row to the destination row. The source row is cleared.
    pub fn move_fields_from(&mut self, src: &mut Self, lookup: &RLookup) {
        for key in lookup.iter() {
            if let Some(value) = src.get(key) {
                self.write_key(key, value.to_owned());
            }
        }
        src.wipe();
    }

    #[track_caller]
    #[cfg(any(debug_assertions, test))]
    pub fn assert_valid(&self, ctx: &str) {
        for val in self.dyn_values.iter().flatten() {
            assert!(
                SharedValue::refcount(val) >= 1,
                "{ctx} - SharedValue refcount must not be zero"
            );
        }
    }
}

pub mod opaque {
    use super::RLookupRow;
    use c_ffi_utils::opaque::Size;

    /// An opaque lookup row which can be passed by value to C.
    ///
    /// The size and alignment of this struct must match the Rust `RLookupRow`
    /// structure exactly.
    #[cheadergen::config(rename = "RLookupRow")]
    #[repr(C, align(8))]
    pub struct OpaqueRLookupRow(Size<24>);

    c_ffi_utils::opaque!(RLookupRow<'_>, OpaqueRLookupRow);
}
