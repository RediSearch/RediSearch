//! Conversions between byte strings and runes.
//!
//! A rune ([`u16`]) is a codepoint truncated to its low 16 bits; tries store
//! and look up terms as rune arrays. Byte strings are decoded with
//! [`nu_codepoints`], so they need not be valid UTF-8, and every conversion
//! ends at the first codepoint 0 that decoding yields.

use crate::libnu::{nu_codepoints, nu_utf8_encode};

/// Maximum number of runes allowed in a single conversion.
pub const MAX_RUNE_STR_LEN: usize = ffi::MAX_RUNE_STR_LEN as usize;

/// Error returned when a rune sequence exceeds [`MAX_RUNE_STR_LEN`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("rune string exceeds the maximum length of {MAX_RUNE_STR_LEN}")]
pub struct RuneStrTooLong;

/// `(codepoint, first codepoint of its case folding)` for every codepoint the
/// folding changes, sorted by codepoint. Generated by `build.rs`.
static CASE_FOLD: &[(u32, u32)] = &include!(concat!(env!("OUT_DIR"), "/case_fold.rs"));

/// Truncate `codepoint` to a rune.
const fn to_rune(codepoint: u32) -> u16 {
    codepoint as u16
}

/// The first codepoint of the full case folding of `codepoint`.
///
/// Folding can map one codepoint to several, as `ß` folds to `ss`; only the
/// first is kept. A codepoint without a folding, including a value that is no
/// Unicode scalar value, maps to itself.
pub fn fold(codepoint: u32) -> u32 {
    if codepoint < 0x80 {
        return (codepoint as u8).to_ascii_lowercase().into();
    }
    match CASE_FOLD.binary_search_by_key(&codepoint, |&(from, _)| from) {
        Ok(i) => CASE_FOLD[i].1,
        Err(_) => codepoint,
    }
}

/// [`fold`] the codepoint `rune` holds, truncating the result to a rune.
pub fn fold_rune(rune: u16) -> u16 {
    to_rune(fold(rune.into()))
}

/// Lowercase `codepoint` without context-dependent rules, as
/// [`char::to_lowercase`] does. A value that is no Unicode scalar value is
/// kept as it is.
fn lowercase(codepoint: u32) -> impl Iterator<Item = u32> {
    let c = char::from_u32(codepoint);
    c.into_iter()
        .flat_map(char::to_lowercase)
        .map(u32::from)
        .chain(c.is_none().then_some(codepoint))
}

/// Collect `runes`, giving up as soon as there are more than
/// [`MAX_RUNE_STR_LEN`], so the input past that point is never decoded.
fn collect_capped(runes: impl Iterator<Item = u16>) -> Result<Vec<u16>, RuneStrTooLong> {
    let mut out = Vec::new();
    for rune in runes {
        if out.len() == MAX_RUNE_STR_LEN {
            return Err(RuneStrTooLong);
        }
        out.push(rune);
    }
    Ok(out)
}

/// Encode `runes` as UTF-8 into `out`, up to the first zero rune, replacing
/// its contents, so a caller converting many keys reuses one buffer.
///
/// Each rune is encoded by its own value with [`nu_utf8_encode`], so a
/// surrogate becomes a three-byte sequence and a surrogate pair is never
/// combined into the character it would denote in UTF-16.
///
/// Returns [`RuneStrTooLong`] if `runes` is longer than [`MAX_RUNE_STR_LEN`],
/// zero runes included, leaving `out` empty.
pub fn runes_to_bytes_into(runes: &[u16], out: &mut Vec<u8>) -> Result<(), RuneStrTooLong> {
    out.clear();
    if runes.len() > MAX_RUNE_STR_LEN {
        return Err(RuneStrTooLong);
    }
    for &rune in runes.iter().take_while(|&&rune| rune != 0) {
        nu_utf8_encode(rune.into(), out);
    }
    Ok(())
}

/// [`runes_to_bytes_into`] into a new vector.
pub fn runes_to_bytes(runes: &[u16]) -> Result<Vec<u8>, RuneStrTooLong> {
    let mut out = Vec::new();
    runes_to_bytes_into(runes, &mut out)?;
    Ok(out)
}

/// Decode `bytes` into runes, truncating each codepoint.
pub fn decode_runes(bytes: &[u8]) -> impl Iterator<Item = u16> + '_ {
    nu_codepoints(bytes).map(to_rune)
}

/// Decode `bytes`, lowercase each codepoint independently and truncate the
/// results to runes. A codepoint can lowercase to several, as `İ` lowercases
/// to `i` followed by a combining dot.
///
/// Returns [`RuneStrTooLong`] once the result exceeds [`MAX_RUNE_STR_LEN`]
/// runes, without decoding the rest of `bytes`.
pub fn lower_runes(bytes: &[u8]) -> Result<Vec<u16>, RuneStrTooLong> {
    collect_capped(nu_codepoints(bytes).flat_map(lowercase).map(to_rune))
}

/// Decode `bytes`, [`fold`] each codepoint and truncate the results to runes.
///
/// Returns [`RuneStrTooLong`] once the result exceeds [`MAX_RUNE_STR_LEN`]
/// runes, without decoding the rest of `bytes`.
pub fn fold_runes(bytes: &[u8]) -> Result<Vec<u16>, RuneStrTooLong> {
    collect_capped(nu_codepoints(bytes).map(|codepoint| to_rune(fold(codepoint))))
}
